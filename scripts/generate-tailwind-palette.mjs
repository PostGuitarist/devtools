import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const OUT_FILE = path.join(process.cwd(), "lib", "tailwind-palette-data.ts");

const css = readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const COLOR_RE =
  /--color-(red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|slate|gray|zinc|neutral|stone)-([0-9]+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+|none)\)/g;
const FAMILY_ORDER = [
  "red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal",
  "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink",
  "rose", "slate", "gray", "zinc", "neutral", "stone",
];

// Converts an OKLCH color (as used by Tailwind v4's default theme) to a
// hex sRGB string, via OKLab then linear sRGB. See Björn Ottosson's OKLab
// reference: https://bottosson.github.io/posts/oklab/
function oklchToHex(L, C, H) {
  const hueDeg = H === "none" ? 0 : parseFloat(H);
  const hueRad = (hueDeg * Math.PI) / 180;
  const a = C * Math.cos(hueRad);
  const b = C * Math.sin(hueRad);

  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.2914855480 * b;
  const l = l_ ** 3;
  const m = m_ ** 3;
  const s = s_ ** 3;

  const rLin = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
  const gLin = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
  const bLin = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s;

  function toSrgb(channel) {
    const clamped = Math.min(1, Math.max(0, channel));
    const gamma =
      clamped <= 0.0031308
        ? clamped * 12.92
        : 1.055 * Math.pow(clamped, 1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, gamma)) * 255);
  }

  return (
    "#" +
    [toSrgb(rLin), toSrgb(gLin), toSrgb(bLin)]
      .map((channel) => channel.toString(16).padStart(2, "0"))
      .join("")
  );
}

const families = {};
let match;
while ((match = COLOR_RE.exec(css))) {
  const [, family, shade, lightnessPct, chroma, hue] = match;
  const lightness = parseFloat(lightnessPct) / 100;
  families[family] ??= [];
  families[family].push({
    shade: parseInt(shade, 10),
    oklch: `oklch(${lightnessPct}% ${chroma} ${hue})`,
    hex: oklchToHex(lightness, parseFloat(chroma), hue),
  });
}

for (const family of FAMILY_ORDER) {
  families[family].sort((a, b) => a.shade - b.shade);
}

const lines = [];
lines.push(
  "// Generated by scripts/generate-tailwind-palette.mjs from tailwindcss/theme.css.",
  "// Do not hand-edit — re-run `bun run generate:tailwind-palette` after a",
  "// Tailwind upgrade that changes the default color palette.",
  "",
  "export interface TailwindSwatch {",
  "  shade: number;",
  "  hex: string;",
  "  oklch: string;",
  "}",
  "",
  "export interface TailwindColorFamily {",
  "  name: string;",
  "  swatches: TailwindSwatch[];",
  "}",
  "",
  "export const tailwindPalette: TailwindColorFamily[] = ["
);
for (const family of FAMILY_ORDER) {
  lines.push(`  {`, `    name: "${family}",`, `    swatches: [`);
  for (const swatch of families[family]) {
    lines.push(
      `      { shade: ${swatch.shade}, hex: "${swatch.hex}", oklch: "${swatch.oklch}" },`
    );
  }
  lines.push(`    ],`, `  },`);
}
lines.push("];", "");

writeFileSync(OUT_FILE, lines.join("\n"));
console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
